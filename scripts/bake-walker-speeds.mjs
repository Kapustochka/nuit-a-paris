// From the repository root: npm i --no-save three@0.170.0
// After changing a walker GLB: node scripts/bake-walker-speeds.mjs
// Pass --check to compare the shipped speeds with fresh samples.
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { AnimationMixer, MeshBasicMaterial } from 'three';
import { GLTFLoader } from 'three/addons/loaders/GLTFLoader.js';
import { MeshoptDecoder } from 'three/addons/libs/meshopt_decoder.module.js';
import { gaitSpeed } from '../src/walker-gait.js';

const models = new URL('../assets/people/3d/', import.meta.url);
const output = new URL('../src/walker-speeds.js', import.meta.url);
const loader = new GLTFLoader().setMeshoptDecoder(MeshoptDecoder);
// Skeleton sampling needs the scene and clip, but no texture decoding.
loader.register(() => ({
  name: 'GaitMeasurement',
  loadMaterial: async () => new MeshBasicMaterial(),
}));

const speeds = {};
for (const file of (await readdir(models)).filter(name => name.endsWith('.glb')).sort()) {
  const bytes = await readFile(new URL(file, models));
  const { scene, animations } = await loader.parseAsync(bytes.buffer.slice(bytes.byteOffset, bytes.byteOffset + bytes.byteLength), '');
  const clip = animations[0];
  if (!clip) throw new Error(`Missing gait clip in ${file}`);
  const mixer = new AnimationMixer(scene);
  mixer.clipAction(clip).play();
  speeds[file.slice(0, -4)] = gaitSpeed(scene, mixer, clip.duration);
}

const source = '// Generated by scripts/bake-walker-speeds.mjs\n' +
  `export const walkerSpeeds = ${JSON.stringify(speeds, null, 2)};\n`;
if (process.argv.includes('--check')) {
  if ((await readFile(output, 'utf8')).replaceAll('\r\n', '\n') !== source) throw new Error('Rebuild walker speeds');
} else {
  await writeFile(output, source);
}
