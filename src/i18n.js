const CYR = /[А-Яа-яЁё]/;
let replace = null;

export function installLanguage() {
  if (CITY.ui !== 'uk') return;
  document.documentElement.dataset.ui = 'uk';
  const keys = Object.keys(UK).sort((a, b) => b.length - a.length);
  const re = new RegExp(keys.map((k) => k.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')).join('|'), 'g');
  replace = (s) => (s && CYR.test(s) ? s.replace(re, (m) => UK[m]) : s);
  const fixText = (node) => { const t = replace(node.nodeValue); if (t !== node.nodeValue) node.nodeValue = t; };
  const LANG = { ru: 'uk', fr: CITY.learn };
  const fixAttrs = (el) => { const l = el.getAttribute?.('lang'); if (LANG[l]) el.setAttribute('lang', LANG[l]); for (const a of ['aria-label', 'title', 'placeholder']) { const v = el.getAttribute?.(a); if (v) { const t = replace(v); if (t !== v) el.setAttribute(a, t); } } };
  const walk = (root) => {
    if (root.nodeType === 3) return fixText(root);
    if (root.nodeType !== 1) return;
    fixAttrs(root);
    const it = document.createTreeWalker(root, NodeFilter.SHOW_TEXT | NodeFilter.SHOW_ELEMENT);
    for (let n = it.nextNode(); n; n = it.nextNode()) n.nodeType === 3 ? fixText(n) : fixAttrs(n);
  };
  walk(document.body);
  new MutationObserver((list) => {
    for (const m of list) {
      if (m.type === 'characterData') fixText(m.target);
      else if (m.type === 'attributes') fixAttrs(m.target);
      else m.addedNodes.forEach(walk);
    }
  }).observe(document.body, { subtree: true, childList: true, characterData: true, attributes: true, attributeFilter: ['aria-label', 'title', 'placeholder', 'lang'] });
}

// For text that never reaches the DOM (alerts, speech, canvas labels)
export const t = (s) => (replace ? replace(s) : s);
